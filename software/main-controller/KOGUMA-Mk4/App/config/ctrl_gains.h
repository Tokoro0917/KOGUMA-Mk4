/*
 * ctrl_gains.h
 * 速度と角度の制御の係数(ctrl/control.c が使う)。ToraNeko.Mk3 の App/config/ctrl_gains.h から(2026-11-28)
 *
 * MK4 は、速度と角度の制御で「左右の電流の目標 [mA]」を決める(ToraNeko は電圧を決めていた)。
 * 電圧への直し(逆起電力・巻線の抵抗・電池の電圧)は ctrl/current_ctrl.c が 20kHz でする(docs/control.md の 4 章)。
 * 電流の目標を、次の 2 つを足して決める(ctrl/control.c の先頭のコメント)。
 *   フィードフォワード: 目標の加速度・角加速度から「これくらい流せば、その加速度になるはず」という電流
 *   フィードバック    : 目標と、測った速さ・角度とのずれを小さくする電流
 * 速さそのものの分(ToraNeko の FF_SPEED_V_PER_MM_S)は、逆起電力として current_ctrl.c が足すので、ここにはない。
 * 値はどれも、計算で出した最初の値(t24 の機体。docs/control.md の 3 章のモデル)。走行ログを見ながら合わせる。
 *
 * ■ 計算に使った値(config/robot_params.h)
 *   タイヤ 1 つの力 = Kt × ギア比 × 電流 ÷ タイヤの半径 = 0.00147 × 5.46 ÷ 0.012 = 0.669 N/A
 *   有効質量 70.2g、慣性モーメント 293 g・cm² + ロータの分(10.1g × (トレッドの半分 29.05mm)²)= 378 g・cm²
 */
#ifndef CONFIG_CTRL_GAINS_H
#define CONFIG_CTRL_GAINS_H

/* ---- フィードフォワード(前に進む分) ---- */

/* 加速度 1mm/s² あたりの、タイヤ 1 つの電流 [mA/(mm/s²)]。
 * 有効質量 × 加速度 = 2 つのタイヤの力 なので、0.0702kg ÷ (2 × 0.669N/A) = 0.0525 A/(m/s²) = 0.0525 mA/(mm/s²)。
 * 加速するところで速さが目標より遅れるなら大きくし、先に行くなら小さくする */
#define FF_ACCEL_MA_PER_MM_S2 0.0525f

/* 動き出すのに要る電流 [mA](床との摩擦の分。タイヤ 1 つ)。仮。
 * 直進で止まる位置が手前になるなら大きくする(ToraNeko は電圧で 0.15V だった。2026-11-03) */
#define FF_FRICTION_MA 30.0f

/* 吸引しているときに、FF_FRICTION_MA に足す電流 [mA](前に進む分)。仮。
 * 吸引で床に押しつけられると、転がりにくさ(摩擦)が増える(ToraNeko は 0.3V。2026-11-03) */
#define FF_SUCTION_FRICTION_MA 60.0f

/* その場旋回で、摩擦に負けないために足す電流 [mA](タイヤ 1 つあたり)。仮(ToraNeko は 0.2V) */
#define FF_TURN_FRICTION_MA 40.0f

/* 角加速度で回すときの、タイヤ 1 つの加速度 1mm/s² あたりの電流 [mA/(mm/s²)](左右で逆向きに流す)。
 * 慣性モーメント × 角加速度 = 2 つのタイヤの力 × トレッドの半分、タイヤの加速度 = 角加速度 × トレッドの半分 なので、
 * 電流 = 慣性モーメント ÷ (2 × 0.669 × (0.02905m)²) × タイヤの加速度 = 3.78e-5 ÷ 0.00113 = 0.0335 A/(m/s²) */
#define FF_TURN_ACCEL_MA_PER_MM_S2 0.0335f

/* 吸引しながらスラロームで曲がるときに、向きの分に足す電流 [mA/(deg/s)](角速度 1deg/s あたり)。仮。
 * 吸引で床に押しつけられて、曲がるときにタイヤが横にこすれる分(ToraNeko は 0.000175V/(deg/s)。2026-11-04) */
#define FF_SUCTION_SLALOM_MA_PER_DEG_S 0.02f

/* ---- 直進の加速度の上限(速さで変わる。ctrl/trajectory.c) ----
 * 速く走っているほど、逆起電力で電圧を使うので、流せる電流が減り、出せる加速度が小さくなる(ToraNeko の 2026-11-11 の考え)。
 *   流せる電流 = (ACCEL_LIMIT_BATTERY_V × 0.95 − Ke × モーターの角速度) ÷ R(電流の上限 CURRENT_LIMIT_MA まで)
 *   モーターが出せる加速度 = (流せる電流 × ACCEL_LIMIT_RATIO − 摩擦の分) ÷ FF_ACCEL_MA_PER_MM_S2
 * 電池の電圧は、走っているあいだの低めの値(3 セル × 3.7V)で見積もる */
#define ACCEL_LIMIT_BATTERY_V 11.1f
#define ACCEL_LIMIT_RATIO 0.8f   /* 加速に使ってよい電流の割合(残りの 2 割はフィードバックの分) */

/* ---- フィードバック(速さ) ---- */

/* 速さのずれ 1mm/s あたりの電流 [mA/(mm/s)](P。タイヤ 1 つ)。
 * 応答を 30Hz にする値: 2π × 30 × 0.0702kg ÷ (2 × 0.669) = 9.9 A/(m/s)(docs/control.md の 4 章「速度・角速度」) */
#define SPEED_KP 10.0f

/* 位置のずれ(速さのずれを足し合わせたもの)1mm あたりの電流 [mA/mm](I)。ToraNeko と同じく SPEED_KP の 10 倍 */
#define SPEED_KI 100.0f

/* ---- フィードバック(向き) ---- */

/* 角速度のずれ 1deg/s あたりの電流 [mA/(deg/s)](P。左右に逆向きに流す)。
 * タイヤ 1 つに 1A 流すと、角加速度は 2 × 0.669 × 0.02905 ÷ 3.78e-5 = 1028 rad/s²。
 * 応答を 30Hz にする値: 2π × 30 ÷ 1028 = 0.183 A/(rad/s) = 3.2 mA/(deg/s) */
#define OMEGA_KP 3.2f

/* 角度のずれ(目標の向き − ジャイロの角度)1deg あたりの電流 [mA/deg](I)。ToraNeko と同じく OMEGA_KP の 50 倍 */
#define ANGLE_KI 160.0f

/* ---- 横の壁に沿って走る補正（直進のときだけ） ---- */

/* 横の壁からのずれ 1 あたり（センサの値の差）、目標の角速度をどれだけ曲げるか [deg/s]（P）。
 * 壁から 1mm 寄るとセンサの値の差が約 290 変わる（2026-10-22 の測定から、おおよその見積もり）ので、
 * 1mm で約 15deg/s 曲げる */
#define WALL_KP 0.05f

/* ずれの変わる速さ 1/s あたり、目標の角速度をどれだけ曲げるか [deg/s]（D）。
 * P だけだと、まん中を通りすぎて左右にゆれ続けるので、ずれが小さくなっていく速さで曲げ方を弱める。
 * 300mm/s で、ゆれが早く収まるように計算した値（減衰比 0.7） */
#define WALL_KD 0.008f

/* 補正で曲げる角速度の上限 [deg/s]。2026-10-24 の探索で、壁の端で読み違えて 90deg/s まで曲げ、
 * 壁に当たったので、45deg/s に下げた */
#define WALL_OMEGA_LIMIT_DEG_S 45.0f

/* ---- 斜めの補正（斜めの直進のとき。ctrl/control.c、しきい値は ctrl/wall_ctrl.c の DIAG_FRONT_*_THRESHOLD） ---- */

/* 前のセンサがしきい値を超えた分 1 あたり、1000mm/s のときに目標の角速度をどれだけ曲げるか [deg/s]。
 * 速さに比例させる（800mm/s なら 0.8 倍）。KOGUMA（Kp_Na）は電圧で曲げているので、値はそのまま持ってこられない。
 * 2026-11-04：横の壁の補正（WALL_KP）と同じにした。しきい値を 900 超えると、800mm/s で 36deg/s 曲げる（上限は下の 45deg/s）。
 * モード3 No.9（補正あり）で、右へずれていく置き方で走らせたら、3 本目の右の柱で右前が 3002 まで上がり、上限の 45deg/s で
 * 左へ 1.9° 曲げて、当たらずに最後まで走れた（logs/20261104-044732_log.txt）。作者が「いい感じ」と見て、この値に決めた。
 * モード3 No.8 の 2 回目（置いたときから右を向いていて、右へずれて柱に当たった。何度ずれていたかはログからはわからない）の
 * ログに当てはめると、1 つ目の柱で、しきい値を超えていた 0.08 秒ほど 45deg/s 近くで曲げて、約 2° 左へ向きを戻す見積もり */
#define DIAG_KP 0.05f

/* ---- 向きを戻す（縦横の直進で、使える横の壁がないとき。2026-11-23 から、斜めの直進で柱や壁が見えていないときも。
 *      ctrl/control.c の先頭のコメント「向きを戻す」。2026-11-04） ---- */

/* 迷路の向きからのずれ 1° あたり、1000mm/s のときに戻す角速度 [deg/s]（速さに比例させる）。
 * 20 なら、ずれは 1000 ÷ 20 = 50mm 進むあいだに戻る（300mm/s なら 0.17 秒、1200mm/s なら 0.04 秒） */
#define HEADING_HOLD_GAIN 20.0f
/* 戻す角速度の上限 [deg/s]（横の壁の補正と同じ） */
#define HEADING_HOLD_LIMIT_DEG_S 45.0f

/* 両側の壁が続いたら、基準の向きをリセットする条件（探索と最短走行）。2026-11-04 に探索のログ（両側に壁、300mm/s）で決めた：
 * ずれ（wall_err）の大きさは、半分の時間で 95 より小さく、ずれの変わる速さは、半分の時間で 835/s より小さかった。
 * 下の値より小さい状態が HEADING_RESET_DISTANCE_MM 続いたら、まん中を壁に平行に走れているとみなす。
 * 変わる速さ 1500/s は、300mm/s で向きが約 0.6° ずれているくらい（両側の壁で、1mm 寄ると約 440 変わる見積もり） */
#define HEADING_RESET_WALL_ERROR_MAX 200.0f   /* 横の壁からのずれ（センサの値の差） */
#define HEADING_RESET_WALL_RATE_MAX  1500.0f  /* ずれの変わる速さ [1/s] */
#define HEADING_RESET_DISTANCE_MM    180.0f   /* この距離続いたらリセットする [mm](クラシックの 1 区画。ToraNeko はハーフの 90mm) */

/* 斜めの補正で曲げる角速度の上限 [deg/s]（横の壁の補正と同じ） */
#define DIAG_OMEGA_LIMIT_DEG_S 45.0f

/* これより遅いときは補正しない [mm/s]（止まる直前・走り出しは、センサの値が目標から離れていても気にしない） */
#define WALL_CONTROL_MIN_SPEED_MM_S 100.0f

/* ---- 前壁合わせ（区画のまん中で止まっているとき、前の壁で位置と向きを直す） ---- */

/* 前の壁との距離のずれ 1 あたりの、目標の速さ [mm/s]（近すぎれば下がる）。
 * 前センサの値は、区画のまん中あたりで 1mm に 100 くらい変わる見積もり（仮）なので、1mm のずれで 30mm/s */
#define ALIGN_SPEED_GAIN 0.3f
#define ALIGN_SPEED_LIMIT_MM_S 50.0f  /* 目標の速さの上限 [mm/s]（100 だと U ターンで下がりすぎたので下げた） */

/* 前壁合わせで、合わせ始めた位置から前後に動いてよい距離 [mm]。
 * 区画のまん中で止まっていれば、ずれは数 mm のはずなので、それより大きく動かさない */
#define ALIGN_DISTANCE_LIMIT_MM 5.0f

/* 前の壁に対する向きのずれ 1 あたりの、目標の角速度 [deg/s]（右を向いていれば左へ回す）（仮） */
#define ALIGN_OMEGA_GAIN 0.2f
#define ALIGN_OMEGA_LIMIT_DEG_S 90.0f  /* 目標の角速度の上限 [deg/s] */

/* ---- 止める条件（フェイルセーフ） ---- */

/* 位置のずれがこれより大きくなったら止める [mm]（ぶつかった、タイヤが空回りした、など） */
#define POSITION_ERROR_LIMIT_MM 30.0f

/* 角度のずれがこれより大きくなったら止める [deg]（モーターの向きが逆、ぶつかって向きが変わった、など） */
#define ANGLE_ERROR_LIMIT_DEG 30.0f

/* 速さで見つける異常（KOGUMA_PORTING.md の F2・F3。2026-11-02。値は仮で、実機で決める）。
 * どちらも、当てはまった状態が FAILSAFE_HOLD_MS 続いたら止める（ノイズ 1 回では止めない。F4） */
#define SPEED_DROP_LIMIT_MM_S   300.0f  /* F2：目標の速さより、測った速さがこれ以上遅い（ぶつかった）[mm/s] */
#define STALL_TARGET_MIN_MM_S   200.0f  /* F3：加速も減速もせず、目標の速さがこれ以上で走っているはずなのに… */
#define STALL_SPEED_MAX_MM_S    50.0f   /*     測った速さがこれより遅い（壁を押し続けている）[mm/s] */
#define FAILSAFE_HOLD_MS        10      /* F4：当てはまった状態がこれだけ続いたら止める [ms] */

#endif /* CONFIG_CTRL_GAINS_H */
